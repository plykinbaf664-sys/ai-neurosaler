export function answerLabel(index: number, key: string) {
  return AI_MAP_QUESTIONS[index]?.options.find(([value]) => value === key)?.[1] ?? "Не уточнено";
}

export function buildAiMapResult(answers: string[], catalog: LibraryMaterialRow[]) {
  if (answers.length !== AI_MAP_QUESTIONS.length || answers.some((a, i) => !AI_MAP_QUESTIONS[i].options.some(([key]) => key === a))) {
    throw new Error("AI map requires five validated answers");
  }
  const scores = new Map(Object.keys(AI_MAP_PROCESSES).map(key => [key, 0]));
  const weights = [0, 4, 2, 3, 3];
  answers.forEach((key, i) => { if (scores.has(key)) scores.set(key, scores.get(key)! + weights[i]); });
  const processKeys = [...scores.keys()].sort((a, b) => scores.get(b)! - scores.get(a)!).slice(0, 3);
  const materials = [...new Map(processKeys.flatMap(key => {
    const material = catalog.find(m => m.is_active && m.slug === AI_MAP_PROCESSES[key].slug);
    return material ? [[material.id, material] as const] : [];
  })).values()];
  const blocks = processKeys.map((key, index) => {
    const p = AI_MAP_PROCESSES[key];
    const evidence = answers.flatMap((a, i) => i > 0 && a === key ? [`«${answerLabel(i, a)}»`] : []);
    const material = materials.find(m => m.slug === p.slug);
    return [`**${index + 1}. ${["🔥", "⚡", "⚙️"][index]} ${p.title}**`,
      evidence.length ? `Ты отметил: ${evidence.join("; ")}.` : "Это гипотеза для проверки: в ответах недостаточно данных, чтобы считать этот процесс проблемой.",
      p.importance, `AI может: ${p.ai}`,
      index === 0 ? "Самостоятельный тест — ниже." : `Проба: ${p.action}`,
      material ? `Готовый сценарий: «${material.title}» — кнопка под картой.` : "",
    ].filter(Boolean).join("\n");
  });
  const first = AI_MAP_PROCESSES[processKeys[0]];
  const firstEvidence = answers.flatMap((key, i) => i > 0 && key === processKeys[0] ? [`«${answerLabel(i, key)}»`] : []);
  const reason = firstEvidence.length
    ? `В ответах ты выделил: ${firstEvidence.join("; ")}. Поэтому я бы сначала проверил этот участок на небольшом примере: он связан с тем, что ты хочешь изменить. Ручной тест покажет, нужна ли здесь автоматизация.`
    : "Ты пока не выделил конкретное узкое место. №1 — стартовая гипотеза для ручного теста, а не диагноз: если задачи нет, автоматизация не нужна.";
  return { processKeys, materialIds: materials.map(m => m.id), text: [
    "**Вот с чего я бы начал у тебя**", `Контекст: ${answerLabel(0, answers[0])}.`, ...blocks,
    "**Если делать только одну вещь — начни с №1.**", reason,
    "**Что можно сделать сегодня**", first.action,
    "Карта — гипотезы по твоим ответам. Начни с ручного теста; перестраивать компанию для него не нужно.",
  ].join("\n\n") };
}

